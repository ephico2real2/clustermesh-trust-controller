assert.equal(emptyReason(producer,'cmtc-authenticated-only',{requireIssuer:true}),undefined);
assert(emptyReason(producer,'cmtc-authenticated-only',{}).includes('Optional issuer'));
assert.equal(emptyReason({title:'ztunnel telemetry coverage',targets:[{expr:'up'}]},'cmtc-authenticated-only',{}),undefined);
assert.equal(emptyReason(leaf(7,'Authenticated connections'),'cmtc-authenticated-only',{requireNative:true}),undefined);
assert(emptyReason(leaf(7,'Authenticated connections'),'cmtc-authenticated-only',{}));
assert.equal(emptyReason(leaf(3,'Controllers'),'cmtc-observe-lab',{}),undefined);
