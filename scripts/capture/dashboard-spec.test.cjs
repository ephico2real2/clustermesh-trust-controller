const assert=require('node:assert/strict');
const {capturePlan,allPanels}=require('./dashboard-spec.cjs');
const leaf=(id,title)=>({id,title,type:'stat',targets:[{expr:'actual_metric'}]});
const fixture={uid:'cmtc-authenticated-only',panels:[leaf(1,'Coverage'),{id:2,title:'Native detail',type:'row',collapsed:true,panels:[leaf(7,'Authenticated connections')]},{id:100,title:'Future trust · planned',type:'row',collapsed:true,panels:[leaf(101,'Trust consumed · planned')]}]};
const compact=capturePlan(fixture);
assert.deepEqual(compact.panels.map(p=>p.id),[1]);
assert.equal(compact.actions.length,0);
assert(compact.blockedCapabilities.includes('Trust consumed · planned'));
assert(compact.blockedCapabilities.some(x=>x.includes('not qualified')));
const native=capturePlan(fixture,{requireNative:true});
assert.deepEqual(native.panels.map(p=>p.id),[1,7]);
assert.deepEqual(native.actions,[{click:'Native detail'},{wait:500}]);
assert(!native.panels.some(p=>p.id===101));
assert(native.blockedCapabilities.includes('Trust consumed · planned'));
assert.equal(allPanels(fixture.panels).filter(p=>p.type!=='row').length,3);
const operations={uid:'cmtc-observe-lab',panels:[leaf(3,'Controllers'),{id:30,title:'Quarantine',type:'row',collapsed:true,panels:[leaf(32,'Quarantine verified')]},{id:40,title:'Observer',type:'row',collapsed:true,panels:[leaf(42,'Observer verified')]}]};
assert.deepEqual(capturePlan(operations,{requireFence:true}).panels.map(p=>p.id),[3,32]);
assert.deepEqual(capturePlan(operations,{requireObserver:true}).panels.map(p=>p.id),[3,42]);
assert.deepEqual(capturePlan(operations,{requireNative:true}).panels.map(p=>p.id),[3]);
const legacy={uid:'cmtc-observe-lab',panels:[{id:2,type:'row',title:'Expanded',collapsed:false},leaf(3,'Controllers'),leaf(100,'Future · planned')]};
assert.deepEqual(capturePlan(legacy).panels.map(p=>p.id),[3,100]);
console.log('PASS compact/expanded capture plans preserve hidden capability blockers and exact visible panel inventories');
