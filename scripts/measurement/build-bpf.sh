#!/usr/bin/env bash
# Compiles the measurement plane's BPF program (internal/measurement/bpf/measure.c) into the object the loader embeds
# (internal/measurement/bpf/measure_bpfel.o), and records the SHA-256 of both in internal/measurement/object_gen.go.
# The unit tests fail when measure.c no longer matches the recorded hash, so run this after every change to it.
#
# The compiler is the pinned Cilium builder (clang 21.1.8), run by digest in a container with no network. The output
# is reproducible: DWARF is stripped (the BTF that the loader needs stays) and no path is recorded.
#
# Usage: scripts/measurement/build-bpf.sh            # compile and write the object and its hashes
#        scripts/measurement/build-bpf.sh --check    # compile into a temporary file and fail if it differs
# Set CONTAINER_ENGINE=podman to use Podman instead of Docker.
set -euo pipefail

builder=quay.io/cilium/cilium-builder@sha256:97d3a0f90898e83c8e63712accb64518f50ae0c4709c423f047c7871e8710ad5
engine=${CONTAINER_ENGINE:-docker}
root=$(cd "$(dirname "$0")/../.." && pwd)
mode=${1:-write}
case "$mode" in
  write | --check) ;;
  *) echo "usage: $0 [--check]" >&2; exit 2 ;;
esac

# Everything runs inside the builder, so the host needs only the container engine (macOS or Linux).
"$engine" run --rm --network none --user "$(id -u):$(id -g)" -e HOME=/tmp -e MODE="$mode" \
  -v "$root:/workspace" -w /workspace --entrypoint bash "$builder" -euo pipefail -c '
src=internal/measurement/bpf/measure.c
obj=internal/measurement/bpf/measure_bpfel.o
gen=internal/measurement/object_gen.go
out=$(mktemp -d)
clang -target bpfel -O2 -g -Wall -Werror -fdebug-compilation-dir=. -c "$src" -o "$out/measure.o"
llvm-strip --strip-debug "$out/measure.o"
object_sha=$(sha256sum "$out/measure.o" | cut -d" " -f1)
source_sha=$(sha256sum "$src" | cut -d" " -f1)
compiler=$(clang --version | head -n 1)
cat > "$out/object_gen.go" <<EOF
// Code generated by scripts/measurement/build-bpf.sh; DO NOT EDIT.

package measurement

// The compiled measurement object embedded by object.go, the source it was compiled from, and the compiler.
const (
	ObjectSHA256       = "$object_sha"
	ObjectSourceSHA256 = "$source_sha"
	ObjectCompiler     = "$compiler"
)
EOF
if [ "$MODE" = --check ]; then
  cmp "$out/measure.o" "$obj" || { echo "$obj differs from a fresh build of $src; run scripts/measurement/build-bpf.sh" >&2; exit 1; }
  cmp "$out/object_gen.go" "$gen" || { echo "$gen differs from a fresh build; run scripts/measurement/build-bpf.sh" >&2; exit 1; }
  echo "$obj and $gen match a fresh build ($object_sha)"
else
  cp "$out/measure.o" "$obj"
  cp "$out/object_gen.go" "$gen"
  echo "wrote $obj ($object_sha) from $src ($source_sha) with $compiler"
fi
rm -rf "$out"
'
